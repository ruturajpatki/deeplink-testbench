import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:deeplink_testbench/main.dart';

void main() {
  testWidgets('App renders title and home screen elements', (WidgetTester tester) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    await tester.pumpWidget(
      const ProviderScope(
        child: RadXDeeplinkApp(),
      ),
    );

    expect(find.text('DeepLink Test Bench'), findsOneWidget);
    expect(find.text('Current Deep-Link State'), findsOneWidget);
  });
}
